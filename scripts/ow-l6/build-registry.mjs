/* Level 6 registers 144 lesson records (9 units × 8 components × teacher+learner).
   Writing 144 import lines into src/data/lessons.ts by hand would bury the
   hand-authored Level 4 registry, so the generator emits one module that
   lessons.ts and reference.ts each spread in. Do not edit the generated files —
   edit scripts/ow-l6/data/unit-<n>.mjs and re-run the build. */
import fs from "node:fs";
import path from "node:path";
import { LEVEL, LEVEL_DIR, ROOT, writeText } from "./lib.mjs";
import { COMPONENTS } from "./build-apps.mjs";

const HEADER = `/* GENERATED by scripts/ow-l6/build.mjs — do not edit by hand.
   Source of truth: scripts/ow-l6/data/unit-<n>.mjs */\n`;

export function buildLessonRegistry(units) {
  const imports = [];
  const entries = [];
  for (const data of units) {
    for (const spec of COMPONENTS) {
      const base = `l6u${data.unit}${spec.file.replace(/[^a-zA-Z0-9]/g, "")}`;
      const dir = `../../${LEVEL_DIR}/unit-${data.unit}/lessons`;
      imports.push(`import ${base}Teacher from "${dir}/${spec.file}.teacher.json";`);
      imports.push(`import ${base}Learner from "${dir}/${spec.file}.learner.json";`);
      entries.push(`  ${base}Teacher as Lesson,`);
      entries.push(`  ${base}Learner as Lesson,`);
    }
  }
  const body = `${HEADER}import type { Lesson } from "./types";
${imports.join("\n")}

export const level6Lessons: Lesson[] = [
${entries.join("\n")}
];
`;
  writeText("src/data/lessons-level6.generated.ts", body);
  return entries.length;
}

export function buildReferenceRegistry(units) {
  const imports = [];
  const vocabularies = [];
  const grammars = [];
  for (const data of units) {
    const dir = `../../${LEVEL_DIR}/unit-${data.unit}`;
    imports.push(`import l6u${data.unit}Vocabulary from "${dir}/vocabulary.json";`);
    imports.push(`import l6u${data.unit}Grammar from "${dir}/grammar.json";`);
    vocabularies.push(`  l6u${data.unit}Vocabulary,`);
    grammars.push(`  l6u${data.unit}Grammar,`);
  }
  const body = `${HEADER}${imports.join("\n")}

/* Every scanned Level 6 unit file, in unit order. reference.ts spreads these so
   Level 6 words and grammar points reach the merged reference layer, the source
   tree, and the vocabulary/grammar browse views without 18 more import lines. */
export const level6Vocabularies = [
${vocabularies.join("\n")}
];

export const level6Grammars = [
${grammars.join("\n")}
];

export const level6UnitTitles: Record<string, string> = Object.fromEntries(
  level6Vocabularies.map((unit) => [\`\${unit.level}-\${unit.unit}\`, unit.unitTitle])
);
`;
  writeText("src/data/reference-level6.generated.ts", body);
  return vocabularies.length;
}

/* The validator reads lessonsDirs as a literal list; keep it in step with the
   units that actually exist on disk. */
export function level6LessonDirs(units) {
  return units.map((data) => `${LEVEL_DIR}/unit-${data.unit}/lessons`);
}

export function assertGeneratedFilesPresent(units) {
  for (const data of units) {
    for (const spec of COMPONENTS) {
      for (const suffix of ["teacher", "learner"]) {
        const file = path.join(ROOT, `${LEVEL_DIR}/unit-${data.unit}/lessons/${spec.file}.${suffix}.json`);
        if (!fs.existsSync(file)) throw new Error(`missing generated lesson record: ${file}`);
      }
    }
  }
  return true;
}

export { LEVEL };
